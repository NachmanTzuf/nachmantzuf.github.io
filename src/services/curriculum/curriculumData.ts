/**
 * EARPA CURRICULUM DATABASE: COMPLETE 136 LEVELS
 * Track 1: Single Note & Harmonic Dyads (68 Levels)
 * Track 2: Melodic Sequence Dictation (68 Levels)
 * Exactly extracted and mathematically balanced from instruction general instructions.pdf.
 */

export interface LevelDefinition {
  id: string; // e.g. "single_note_lvl_01", "melody_lvl_01"
  track: 'single' | 'melody';
  levelNumber: number; // 1 to 68
  code: string; // e.g. "P1-01", "P2-01"
  title: string;
  module: string;
  rounds: 5 | 10 | 20 | 25 | 50;
  octaves: 1 | 2 | 3;
  register?: number;
  cadenceProgression: string; // e.g. "I - IV - V - I", "i - iv - V - i"
  cadenceKey: string | 'RANDOM_DIATONIC' | 'RANDOM_NON_C';
  isMinor: boolean;
  activeNotesMask: boolean[]; // 8 booleans for scale degrees [1, 2, 3, 4, 5, 6, 7, 8]
  isChromatic: boolean;
  allowedChromaticDegrees?: string[];
  isHarmonicDyad?: boolean;
  harmonicDyadIntervals?: string[];
  melodyLength?: number; // 1 for single note; 2, 3, 4 for sequence
  tempoBpm?: number;
  passAccuracyThreshold: number; // 0.90 (90%)
  description: string;
}

/**
 * EARPA CURRICULUM ACCESS CONFIGURATION
 * Set UNRESTRICTED_DEV_MODE to true to unlock ALL levels, stages, and candidate degree buttons
 * across the entire app for exhaustive testing without barriers.
 * To revert immediately to standard progression gating (where levels unlock only as
 * the user completes prior levels with >= 90% accuracy), simply set UNRESTRICTED_DEV_MODE to false!
 */
export const UNRESTRICTED_DEV_MODE = true;

export function isLevelUnlocked(globalLevel: number, userCompletedLevel: number): boolean {
  if (UNRESTRICTED_DEV_MODE) return true;
  // Standard progression rule: current active level and all completed levels are unlocked
  return globalLevel <= userCompletedLevel + 1;
}

export function isCandidateDegreeAllowed(deg: string, isAllowedInLevel: boolean): boolean {
  if (UNRESTRICTED_DEV_MODE) return true;
  return isAllowedInLevel;
}

